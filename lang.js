// State variables
let currentLang = localStorage.getItem('site_lang') || 'tr';

// Function to traverse text nodes safely and translate
function walkAndTranslate(node, lang) {
    if (node.nodeType === 3) { // Text node
        const text = node.nodeValue.trim();
        // If not empty, try translating
        if (text) {
            // Check if we have an original stored
            if (!node._origText) {
                node._origText = text;
            }
            const orig = node._origText;
            
            if (lang === 'en' && dictionary[orig]) {
                node.nodeValue = node.nodeValue.replace(orig, dictionary[orig]);
            } else if (lang === 'tr') {
                node.nodeValue = node.nodeValue.replace(text, orig);
            }
        }
    } else if (node.nodeType === 1 && node.nodeName !== "SCRIPT" && node.nodeName !== "STYLE") { // Element node
        // Translate placeholders
        if (node.placeholder) {
            if (!node._origPlaceholder) node._origPlaceholder = node.placeholder.trim();
            const origP = node._origPlaceholder;
            if (lang === 'en' && dictionary[origP]) node.placeholder = dictionary[origP];
            else if (lang === 'tr') node.placeholder = origP;
        }
        
        // Translate aria-labels
        const ariaLabel = node.getAttribute('aria-label');
        if (ariaLabel) {
            if (!node._origAria) node._origAria = ariaLabel.trim();
            const origA = node._origAria;
            if (lang === 'en' && dictionary[origA]) node.setAttribute('aria-label', dictionary[origA]);
            else if (lang === 'tr') node.setAttribute('aria-label', origA);
        }

        // Translate specific elements that might not have raw text nodes directly handled cleanly
        // (This covers most normal DOM children)
        for (let i = 0; i < node.childNodes.length; i++) {
            walkAndTranslate(node.childNodes[i], lang);
        }
    }
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('site_lang', lang);
    
    // Update body class or HTML lang attr for CSS and accessibility
    document.documentElement.lang = lang;

    // Traverse the DOM starting from body
    walkAndTranslate(document.body, lang);
    
    // Handle the Title manually
    if (!document._origTitle) document._origTitle = document.title;
    if (lang === 'en' && dictionary[document._origTitle]) {
        document.title = dictionary[document._origTitle];
    } else if (lang === 'tr') {
        document.title = document._origTitle;
    }

    // Update active class on buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.textContent.trim().toLowerCase() === lang.toLowerCase()) {
            btn.classList.add('active');
        }
    });
}

// Initialization on load
document.addEventListener('DOMContentLoaded', () => {
    // Bind click events to language buttons
    const langBtns = document.querySelectorAll('.lang-btn');
    langBtns.forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const selectedLang = btn.textContent.trim().toLowerCase();
            // Handle only tr and en for now
            if (selectedLang === 'tr' || selectedLang === 'en') {
                setLanguage(selectedLang);
            }
        });
    });

    // Apply initial language if not Turkish
    if (currentLang !== 'tr') {
        // We defer this slightly so other JS modifications can finish first, if any
        setTimeout(() => setLanguage(currentLang), 100);
    }
});
